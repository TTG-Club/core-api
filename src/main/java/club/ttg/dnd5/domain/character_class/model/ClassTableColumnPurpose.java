package club.ttg.dnd5.domain.character_class.model;

/**
 * Что означает колонка таблицы прогрессии для листа персонажа и для мастера повышения
 * уровня.
 *
 * <p>Колонка «Известные заговоры» и колонка «Скрытая атака» выглядят в таблице одинаково —
 * подпись и значения по уровням, — но означают разное: первая говорит мастеру, сколько
 * заговоров спросить у игрока на этом уровне, вторая только показывается. Без явного
 * признака потребитель угадывал бы назначение по подписи, а на переведённых и самописных
 * классах шаг молча пропадал бы.</p>
 */
public enum ClassTableColumnPurpose {
    /** Обычная колонка: только показывается в таблице. */
    NONE,

    /** Всего известно заговоров на этом уровне. */
    CANTRIPS_KNOWN,

    /** Всего известно заклинаний 1+ круга на этом уровне (классы «знающих»). */
    SPELLS_KNOWN,

    /** Всего подготовлено заклинаний на этом уровне (классы «подготавливающих»). */
    PREPARED_SPELLS
}
