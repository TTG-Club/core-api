package club.ttg.dnd5.domain.character_class.model;

/**
 * Когда игрок может заменить один ранее выбранный вариант умения на другой.
 *
 * <p>По правилам замена есть не у всех выбираемых списков: таинственное воззвание
 * колдун меняет на любом новом уровне, манёвр мастера боевых искусств (2014) — только
 * на уровне, где берёт новые манёвры, а боевой стиль не меняется вовсе. Признак лежит
 * в {@link ClassFeatureOptionsChoice#getReplacement()}; его отсутствие означает, что
 * замены нет.</p>
 */
public enum ClassFeatureOptionReplacement {
    /** На каждом новом уровне класса можно заменить один выбранный вариант на другой доступный. */
    EVERY_LEVEL,

    /**
     * Замена только на уровнях, где у выбора есть ступень: уровень получения умения или
     * ступень {@link ClassFeatureOptionsChoice#getScaling()}.
     */
    CHOICE_LEVELS
}
