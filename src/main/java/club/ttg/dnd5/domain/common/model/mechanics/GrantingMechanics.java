package club.ttg.dnd5.domain.common.model.mechanics;

import club.ttg.dnd5.domain.common.model.AbilityBonus;

import java.util.List;

/**
 * Общий вид механики записи справочника, которая что-то ВЫДАЁТ листу персонажа.
 *
 * <p>Такой механикой обзавелись черта, предыстория, вид и класс. Блоки у них одни и те же —
 * модификаторы, владения, выборы, заклинания, ресурсы, — и различаются они только тем,
 * какие из блоков имеют смысл: у вида не бывает повышения характеристик, у предыстории —
 * ресурсов. Общий вид позволяет писать разбор один раз: выгрузка в VTTG собирает
 * {@code featData} одним кодом для всех четырёх.</p>
 *
 * <p>Блоки, которых у конкретной записи нет, отдают {@code null} — так же, как незаполненный
 * блок у той записи, где он есть. Потребителю разницы нет.</p>
 */
public interface GrantingMechanics {
    /** Постоянные модификаторы листа: хиты, скорости, КД, чувства, защиты. */
    SheetModifiers getModifiers();

    /** Владения, выданные без выбора. */
    ProficiencyGrant getProficiencies();

    /** Выборы, которые игрок делает при получении. */
    List<MechanicChoice> getChoices();

    /** Заклинания, выданные без выбора; {@code null} — запись их не выдаёт. */
    default SpellGrant getSpells() {
        return null;
    }

    /** Расширение списка заклинаний класса; {@code null} — запись его не расширяет. */
    default SpellListExpansion getSpellList() {
        return null;
    }

    /** Ресурсы со счётчиком; {@code null} — запись их не даёт. */
    default List<ResourceCounter> getCounters() {
        return null;
    }

    /**
     * Варианты повышения характеристик; {@code null} — запись их не поднимает.
     *
     * <p>По правилам 2024 года характеристики поднимают черта и предыстория, а вид и класс —
     * нет: у класса это отмечено флагом умения, и второе место для того же самого
     * разошлось бы с первым.</p>
     */
    default List<AbilityBonus> getAbilityBonuses() {
        return null;
    }
}
