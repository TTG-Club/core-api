package club.ttg.dnd5.domain.common.model.mechanics;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Что даёт сделанный выбор — владение или компетентность.
 *
 * <p>Компетентность удваивает бонус мастерства в значении навыка, поэтому это не
 * «владение посильнее», а другой исход: «Знаток» просит выбрать навык, которым
 * персонаж уже владеет, и поднимает его сразу до компетентности.</p>
 *
 * <p>От флага {@code expertiseIfProficient} отличается безусловностью. Тот описывает
 * замену: владеешь выбранным — получишь компетентность, не владеешь — получишь
 * владение («Наблюдательный», «Острый ум»). Здесь исход один и тот же всегда.</p>
 */
@Getter
@AllArgsConstructor
public enum ChoiceGrant {
    PROFICIENCY("владение"),
    EXPERTISE("компетентность");

    private final String name;
}
