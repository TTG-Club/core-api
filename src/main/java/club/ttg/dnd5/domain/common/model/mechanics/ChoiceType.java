package club.ttg.dnd5.domain.common.model.mechanics;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Что именно выбирает игрок. Набор вырос из разбора описаний 294 черт прода: типов,
 * которых в тексте не нашлось, здесь нет. Разбор 135 умений видов новых типов не добавил —
 * виды выбирают навык, инструмент, тип урона и заклинательную характеристику, и всё это
 * здесь уже есть.
 *
 * <p>Исключение — {@link #ARMOR}: доспехов на выбор в справочнике нет, но лист такой выбор
 * применяет, а хоумбрю его просит. Тип заведён ради него, а не ради книжной черты.</p>
 *
 * <p>Виды делятся на те, у которых есть справочник правил ({@link #SKILL}, {@link #TOOL},
 * {@link #LANGUAGE}, {@link #ABILITY}, {@link #SAVING_THROW}, {@link #SPELLCASTING_ABILITY},
 * {@link #DAMAGE_TYPE}, {@link #SPELL_LIST}, {@link #ARMOR}), и те, чьи значения описаны
 * данными мира или компендиума ({@link #WEAPON}, {@link #WEAPON_MASTERY}, {@link #SPELL},
 * {@link #CANTRIP}, {@link #OPTION}). Смешивать в одном выборе
 * ({@link MechanicChoice#getTypes()}) можно только первые: у вторых значение по себе не
 * говорит, какому виду оно принадлежит.</p>
 */
@Getter
@AllArgsConstructor
public enum ChoiceType {
    /** Характеристика вне повышения и спасбросков. */
    ABILITY("характеристика"),
    /** Характеристика, спасбросками которой персонаж овладевает: «Устойчивый», «Здоровяк». */
    SAVING_THROW("спасбросок"),
    SKILL("навык"),
    /** Инструмент, набор или музыкальный инструмент — предмет справочника. */
    TOOL("инструмент"),
    LANGUAGE("язык"),
    /** Тип урона: «Адепт стихий», «Отмеченный драконом», «Дар устойчивости к энергиям». */
    DAMAGE_TYPE("тип урона"),
    SPELL("заклинание"),
    CANTRIP("заговор"),
    /** Список заклинаний класса-источника: «Посвящённый в магию». */
    SPELL_LIST("список заклинаний"),
    /** Интеллект, Мудрость или Харизма как характеристика заклинаний этой черты. */
    SPELLCASTING_ABILITY("заклинательная характеристика"),
    /** Вид оружия: «Мастер оружия» выбирает тип простого или воинского оружия. */
    WEAPON("оружие"),
    /**
     * Оружейный приём (weapon mastery, 2024): «Мастер оружия» выбирает виды оружия, чьими
     * приёмами владеет.
     *
     * <p>Отдельным типом от {@link #WEAPON}, хотя значения у них общие — виды оружия: на
     * листе это разные списки владений ({@code proficiencies.weapons} против
     * {@code proficiencies.weaponMasteries}), и приём не подмножество владения. «Мастер
     * оружия» даёт и то, и другое, но разными строками.</p>
     */
    WEAPON_MASTERY("оружейный приём"),
    /** Категория доспехов: лёгкие, средние, тяжёлые, щиты. */
    ARMOR("доспехи"),
    /** Вариант из списка, своего у каждой черты: метка дракона, дисциплина, благословение. */
    OPTION("вариант"),
    /**
     * Черта справочника: умение класса даёт выбрать черту — боевой стиль на первом уровне
     * воина, любую общую черту на уровне повышения характеристик.
     *
     * <p>Значение — url черты. Пул задаётся двумя способами, и оба могут стоять разом:
     * перечислением в {@link MechanicChoice#getOptions()} («любой из этих трёх стилей») и
     * категориями в {@link MechanicChoice#getFeatCategories()} («любой боевой стиль»). Пусто
     * и то, и другое — любая черта справочника.</p>
     *
     * <p>Значение описано данными справочника, а не правил, поэтому смешивать этот вид с
     * другими в одном наборе нельзя — как оружие и заклинание.</p>
     */
    FEAT("черта");

    private final String name;
}
