package club.ttg.dnd5.domain.common.model.mechanics;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Что именно выбирает игрок. Набор вырос из разбора описаний 294 черт прода: типов,
 * которых в тексте не нашлось, здесь нет. Разбор 135 умений видов новых типов не добавил —
 * виды выбирают навык, инструмент, тип урона и заклинательную характеристику, и всё это
 * здесь уже есть.
 */
@Getter
@AllArgsConstructor
public enum ChoiceType {
    /** Характеристика вне повышения и спасбросков. */
    ABILITY("характеристика"),
    /** Характеристика, спасбросками которой персонаж овладевает: «Устойчивый», «Здоровяк». */
    SAVING_THROW("спасбросок"),
    SKILL("навык"),
    /** Инструмент, набор или музыкальный инструмент — предмет справочника. */
    TOOL("инструмент"),
    LANGUAGE("язык"),
    /** Тип урона: «Адепт стихий», «Отмеченный драконом», «Дар устойчивости к энергиям». */
    DAMAGE_TYPE("тип урона"),
    SPELL("заклинание"),
    CANTRIP("заговор"),
    /** Список заклинаний класса-источника: «Посвящённый в магию». */
    SPELL_LIST("список заклинаний"),
    /** Интеллект, Мудрость или Харизма как характеристика заклинаний этой черты. */
    SPELLCASTING_ABILITY("заклинательная характеристика"),
    /** Вид оружия: «Мастер оружия» выбирает тип простого или воинского оружия. */
    WEAPON("оружие"),
    /** Вариант из списка, своего у каждой черты: метка дракона, дисциплина, благословение. */
    OPTION("вариант");

    private final String name;
}
