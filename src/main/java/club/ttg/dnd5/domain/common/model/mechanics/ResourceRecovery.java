package club.ttg.dnd5.domain.common.model.mechanics;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * Каким отдыхом восстанавливается ресурс.
 *
 * <p>«Не восстанавливается» отдельным значением не заводится — такой счётчик и ресурсом
 * не является, его нечем откатывать.</p>
 *
 * <p>Короткий отдых в правилах короче продолжительного, поэтому ресурс, который вернул
 * короткий, возвращает и продолжительный: {@link #SHORT_REST} и {@link #SHORT_REST_ONE}
 * различаются только порцией короткого отдыха.</p>
 */
@Getter
@AllArgsConstructor
public enum ResourceRecovery {
    SHORT_REST("короткий отдых"),
    LONG_REST("продолжительный отдых"),
    /**
     * Один заряд на коротком отдыхе, все — на продолжительном: так устроены «Второе
     * дыхание» и «Вдохновение барда» правил 2024 года.
     */
    SHORT_REST_ONE("один заряд на коротком отдыхе, все — на продолжительном");

    private final String name;
}
