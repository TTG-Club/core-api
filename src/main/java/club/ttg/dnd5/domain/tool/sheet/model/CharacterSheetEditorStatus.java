package club.ttg.dnd5.domain.tool.sheet.model;

/**
 * Состояние права на редактирование чужого листа.
 */
public enum CharacterSheetEditorStatus {
    /** Запрос отправлен, владелец ещё не ответил. */
    PENDING,
    /** Владелец разрешил: лист открывается и сохраняется редактором. */
    APPROVED,
    /**
     * Отказ из прежних версий. Сейчас отказ и отзыв запись удаляют, а такой статус при новом запросе
     * сразу становится ждущим.
     */
    DECLINED
}
