package club.ttg.dnd5.domain.article.model;

/**
 * Вид поста новости / статьи в Telegram-канале — выбирается в админке для каждой записи.
 * <p>
 * NULL у записей до миграции читается как {@link #INSTANT_VIEW} — прежнее поведение: вид определял
 * только конфиг ({@code telegram.instant-view-rhash}).
 */
public enum TelegramPostFormat {
    /**
     * Карточка Instant View: одно сообщение со ссылкой {@code t.me/iv?url=…&rhash=…} — обложку, заголовок
     * и анонс показывает превью, полный текст открывается в Telegram по кнопке на карточке.
     * <p>
     * Требует настроенного {@code telegram.instant-view-rhash} и публичного {@code app.url}; без них
     * (локально, шаблон ещё не создан) пост автоматически уходит как {@link #FULL_TEXT}.
     */
    INSTANT_VIEW,

    /**
     * Прежний вид: полный текст новости в самом посте (при необходимости несколькими сообщениями),
     * обложка — превью над текстом либо фото с подписью. Выбирают, когда текст должен читаться
     * прямо в ленте канала, без перехода в Instant View.
     */
    FULL_TEXT
}
