package club.ttg.dnd5.domain.article.model;

/**
 * Пинг участников канала при публикации новости в Discord — выбирается в админке.
 * <p>
 * Звеним ровно один раз: пинг идёт только с ПЕРВЫМ сообщением поста, хвостовые части длинной новости
 * и синхронизация правки отправляются с запретом упоминаний. При ручной публикации поста подписчикам
 * («Опубликовать» в announcement-канале) Discord вырезает упоминания из копии — чужие серверы от
 * нашего пинга не звенят.
 */
public enum DiscordMention {
    /** Без пинга: @everyone/@here/роли, случайно попавшие в текст новости, тоже не звенят. */
    NONE,
    /** {@code @everyone} — всем участникам сервера. */
    EVERYONE,
    /** Роль server — её id задаётся в конфиге ({@code discord.server-role-id}). */
    SERVER
}
