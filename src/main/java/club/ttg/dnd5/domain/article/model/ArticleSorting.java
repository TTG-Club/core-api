package club.ttg.dnd5.domain.article.model;

/**
 * Сортировка публичного листинга статей / новостей.
 */
public enum ArticleSorting {
    /**
     * По дате выхода, новые сверху (по умолчанию).
     */
    DATE,
    /**
     * По названию, по алфавиту.
     */
    TITLE,
    /**
     * По рейтингу: средняя оценка, затем число оценок, обе по убыванию.
     */
    RATING
}
