package club.ttg.dnd5.domain.beastiary.model.spellcasting;

/**
 * Чем ограничены применения порции заклинаний.
 *
 * <p>Существо редакции 2024 ячеек не тратит: у порции либо неограниченное применение,
 * либо счётчик. Счётчик бывает двух смыслов, и путать их нельзя — «1/день каждое» даёт
 * по применению КАЖДОМУ заклинанию порции, а «1/день» даёт одно применение на ВСЮ
 * порцию. Отдых, перезарядка и постоянное действие встречаются у одиночных записей
 * («Щит (1/отдых)», «Очарование (перезарядка 5–6)») и заводятся тем же блоком.</p>
 *
 * <p>Зеркало {@code CreatureSpellUsageMode} формы сайта: значения приходят и уходят
 * этими именами.</p>
 */
public enum CreatureSpellUsageMode {
    AT_WILL,
    PER_DAY_EACH,
    PER_DAY_POOL,
    PER_REST_EACH,
    PER_REST_POOL,
    RECHARGE,
    CONSTANT
}
